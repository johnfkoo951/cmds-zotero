/**
 * 0.6.1 zotero-menu-actions-recipe: the text of an Actions & Tags `customScript` that a person pastes into Zotero
 * themselves. From an item or reader menu, a shortcut or an event it launches this plugin's existing
 * `obsidian://cmds-zotero` link (`target=note` opens the literature note, `target=import` its import preview) through
 * `Zotero.launchURL`. Nothing is installed into Zotero and nothing in Zotero is changed by the script. Pure: no `obsidian`
 * import.
 */

export type ZoteroScriptTarget = "note" | "import";

export const ZOTERO_SCRIPT_TARGETS: readonly { target: ZoteroScriptTarget; name: string; description: string; command: string }[] = [
	{ target: "note", name: "Open literature note", description: "Opens the item's literature note in this vault (or reports that none exists yet).", command: "Open Zotero selection" },
	{ target: "import", name: "Preview literature import", description: "Opens the import preview for the item in this vault; nothing is written until you confirm.", command: "Import Zotero selection" },
];

/** The link the script launches for one Zotero item (`libraryID` is Zotero's local library ID). */
export function zoteroScriptURL(vault: string, target: ZoteroScriptTarget, libraryID: number, itemKey: string): string {
	return `obsidian://cmds-zotero?vault=${encodeURIComponent(vault)}&libraryID=${libraryID}&itemKey=${itemKey}&target=${target}`;
}

/** A JavaScript string literal for `value` (JSON, with the two line separators JSON leaves raw escaped too). */
function literal(value: string): string {
	return JSON.stringify(value).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
}

/**
 * The customScript for `vault` and `target`. Actions & Tags runs a menu or shortcut action once with every selected item
 * (`items`, `item` undefined) and then once per item (`items` empty, `item` set); events run it once with `item` and
 * `items` null. The script acts on the first run only. Attachments, notes and annotations stand for their parent item;
 * with more than one item it launches nothing and names the Obsidian command that handles several.
 */
export function zoteroActionScript(vault: string, target: ZoteroScriptTarget): string {
	const spec = ZOTERO_SCRIPT_TARGETS.find(row => row.target === target);
	if (!spec) throw new Error(`Unknown script target: ${String(target)}`);
	return [
		`// CMDS Zotero: ${spec.name.toLowerCase()} in Obsidian. Actions & Tags customScript; needs Zotero 10.0.3 or later.`,
		"// Generated by the Obsidian command \"Copy Zotero action script\". It only launches an obsidian:// link.",
		`const VAULT = ${literal(vault)};`,
		`const TARGET = ${literal(target)};`,
		"// A menu or shortcut runs this once with all selected items, then once per item with `items` empty: act on the first run only.",
		"if (item && Array.isArray(items) && items.length === 0) return;",
		"const Zotero = require(\"Zotero\");",
		"const parentOf = entry => {",
		"  let current = entry;",
		"  for (let depth = 0; current && depth < 2 && !current.isRegularItem(); depth++) current = current.parentItem;",
		"  return current && current.isRegularItem() ? current : null;",
		"};",
		"const chosen = new Map();",
		"for (const entry of (items && items.length ? items : item ? [item] : [])) {",
		"  const parent = parentOf(entry);",
		"  if (parent) chosen.set(parent.libraryID + \":\" + parent.key, parent);",
		"}",
		"if (chosen.size === 0) return;",
		"if (chosen.size > 1) {",
		`  Zotero.getMainWindow().alert(${literal(`CMDS Zotero: select one item. For several items, run "${spec.command}" in Obsidian.`)});`,
		"  return;",
		"}",
		"const [parent] = chosen.values();",
		"Zotero.launchURL(\"obsidian://cmds-zotero?vault=\" + encodeURIComponent(VAULT) + \"&libraryID=\" + parent.libraryID + \"&itemKey=\" + parent.key + \"&target=\" + TARGET);",
		"",
	].join("\n");
}
