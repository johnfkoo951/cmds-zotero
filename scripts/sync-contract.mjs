#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(join(root, 'docs/agent-contract-v2/contract.md'), 'utf8');
const generated = '<!-- Generated by scripts/sync-contract.mjs from docs/agent-contract-v2/contract.md. -->\n' + source.replace('Normative supplement to [the 0.4 implementation plan](../0.4-agent-contract-plan.md).', 'Normative agent contract distributed with the CMDS Zotero skill.');
const target = join(root, 'skills/cmds-zotero/references/cli-contract-v2.md');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) {
    console.error('Agent contract reference is stale; run node scripts/sync-contract.mjs.');
    process.exitCode = 1;
  }
} else {
  await writeFile(target, generated);
}
