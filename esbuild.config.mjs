import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { coreBuildOptions } from "./scripts/core-build.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const mode = process.argv[2];

if (mode === "core") {
  // Offline CLI core: pure modules plus the `yaml` package, no `obsidian` import allowed (verified by tests/tooling.test.ts).
  await esbuild.build(coreBuildOptions);
  process.exit(0);
}

const prod = mode === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // 0.6.2: the editor extension uses Obsidian's own CodeMirror instance, never a bundled copy.
  external: ["obsidian", "electron", "@codemirror/state", "@codemirror/view", "node:*", ...builtinModules],
  platform: "node",
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
