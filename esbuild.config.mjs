import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const mode = process.argv[2];

if (mode === "core") {
  // Offline CLI core: pure modules plus the `yaml` package, no `obsidian` import allowed (verified by tests/tooling.test.ts).
  await esbuild.build({
    banner: { js: banner },
    entryPoints: ["src/cli/core.ts"],
    bundle: true,
    external: ["obsidian", "electron", "node:*", ...builtinModules],
    platform: "node",
    format: "esm",
    target: "node22",
    logLevel: "warning",
    sourcemap: false,
    minify: false,
    treeShaking: true,
    outfile: "scripts/ingest-core.mjs",
  });
  process.exit(0);
}

const prod = mode === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: ["obsidian", "electron", "node:*", ...builtinModules],
  platform: "node",
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
